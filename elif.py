num = int (input ("Enter a number for a day"))
if num == 1:
    print("Today is Monday")
elif num == 2:
    print("Its Tuesday")
elif num == 3:
    print("Its Wednesday")
elif num == 4:
    print("Its Thursday")
elif num == 5:
    print("Its Friday")
elif num == 6:
    print("Its Saturday")
elif num == 7:
    print("Its Sunday")
else :
    print("Invalid")